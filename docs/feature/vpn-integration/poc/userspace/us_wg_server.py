#!/usr/bin/env python3
"""Userspace-VPN PoC — simulated Proton exit (test infrastructure only, NOT the app container).

Runs in the `vpnpoc-wg` container (NET_ADMIN + ip_forward, air-gapped `--internal` networks):
  * kernel WireGuard peer `wg0` 10.2.0.1/24 (client 10.2.0.2/32), ListenPort 51820 on the WAN net;
  * NAT: tunnel traffic leaves to the swarm net masqueraded (the "VPN exit IP" = 172.30.20.2);
  * port forward: 172.30.20.2:16881/tcp -> 10.2.0.2:6881 (stands in for a Proton NAT-PMP mapping);
  * DNS on 10.2.0.1:53/udp: tracker.poc.test / dht.poc.test -> 172.30.20.2, everything else NXDOMAIN;
  * HTTP tracker on :6969 (compact peers) plus a UDP :6969 listener that only logs.
Every DNS query, announce and UDP tracker packet is logged with its source to /share/server_events.json.
Test keys are generated by the orchestrator into /share/wg (never printed).
"""

import json
import socket
import struct
import subprocess
import threading
import time
import urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

SHARE = Path("/share")
SWARM_IP = "172.30.20.2"
DNS_RECORDS = {"tracker.poc.test.": SWARM_IP, "dht.poc.test.": SWARM_IP}
LOCK = threading.Lock()
EVENTS: dict[str, list] = {"dns_queries": [], "announces": [], "udp_tracker_packets": []}
SWARM: dict[bytes, dict[tuple[str, int], float]] = {}


def run(*cmd: str) -> None:
    subprocess.run(cmd, check=True)


def iface_with_ip(ip: str) -> str:
    out = json.loads(subprocess.check_output(["ip", "-j", "addr"], text=True))
    for link in out:
        if any(a.get("local") == ip for a in link.get("addr_info", [])):
            return link["ifname"]
    raise SystemExit(f"no interface with {ip}")


def setup() -> None:
    swarm_if = iface_with_ip(SWARM_IP)
    client_pub = (SHARE / "wg/client.pub").read_text().strip()
    run("ip", "link", "add", "wg0", "type", "wireguard")
    run("wg", "set", "wg0", "listen-port", "51820", "private-key", str(SHARE / "wg/server.key"),
        "peer", client_pub, "allowed-ips", "10.2.0.2/32")
    run("ip", "addr", "add", "10.2.0.1/24", "dev", "wg0")
    run("ip", "link", "set", "wg0", "up")
    rules = f"""
table ip vpnpoc {{
  chain pre {{
    type nat hook prerouting priority -100; policy accept;
    iifname "{swarm_if}" tcp dport 16881 dnat to 10.2.0.2:6881
  }}
  chain post {{
    type nat hook postrouting priority 100; policy accept;
    oifname "{swarm_if}" ip saddr 10.2.0.0/24 masquerade
  }}
}}
"""
    subprocess.run(["nft", "-f", "-"], input=rules, text=True, check=True)


def qname(packet: bytes) -> str:
    labels, i = [], 12
    while packet[i]:
        n = packet[i]
        labels.append(packet[i + 1:i + 1 + n].decode("ascii", "replace"))
        i += 1 + n
    return ".".join(labels).lower() + "."


def serve_dns() -> None:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.bind(("10.2.0.1", 53))
    while True:
        data, addr = s.recvfrom(2048)
        try:
            name = qname(data)
            qtype = struct.unpack("!H", data[12 + len(name) + 1:12 + len(name) + 3])[0] if len(data) > 16 else 0
        except Exception:
            continue
        with LOCK:
            EVENTS["dns_queries"].append({"t": time.time(), "src": addr[0], "name": name, "qtype": qtype})
        end = 12 + len(name) + 1 + 4
        question = data[12:end]
        ip = DNS_RECORDS.get(name)
        if ip and qtype == 1:
            header = data[:2] + b"\x81\x80" + b"\x00\x01\x00\x01\x00\x00\x00\x00"
            answer = b"\xc0\x0c\x00\x01\x00\x01\x00\x00\x00\x3c\x00\x04" + socket.inet_aton(ip)
            s.sendto(header + question + answer, addr)
        else:
            rcode = b"\x81\x80" if ip else b"\x81\x83"  # NOERROR (no AAAA) / NXDOMAIN
            s.sendto(data[:2] + rcode + b"\x00\x01\x00\x00\x00\x00\x00\x00" + question, addr)


def serve_udp_tracker_logger() -> None:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.bind(("0.0.0.0", 6969))
    while True:
        data, addr = s.recvfrom(2048)
        with LOCK:
            EVENTS["udp_tracker_packets"].append({"t": time.time(), "src": addr[0], "len": len(data)})


def bencode(value) -> bytes:
    if isinstance(value, int):
        return b"i%de" % value
    if isinstance(value, bytes):
        return b"%d:%s" % (len(value), value)
    if isinstance(value, str):
        return bencode(value.encode())
    if isinstance(value, dict):
        return b"d" + b"".join(bencode(k) + bencode(v) for k, v in sorted(value.items())) + b"e"
    raise TypeError(type(value))


class Tracker(BaseHTTPRequestHandler):
    def log_message(self, *args):  # quiet
        pass

    def do_GET(self):
        parsed = urllib.parse.urlsplit(self.path)
        if parsed.path != "/announce":
            self.send_error(404)
            return
        q = urllib.parse.parse_qs(parsed.query, keep_blank_values=True, encoding="latin-1")
        info_hash = q["info_hash"][0].encode("latin-1")
        port = int(q.get("port", ["0"])[0])
        src = self.client_address[0]
        event = q.get("event", [""])[0]
        now = time.time()
        with LOCK:
            EVENTS["announces"].append({"t": now, "src": src, "port": port, "event": event})
            peers = SWARM.setdefault(info_hash, {})
            if event == "stopped":
                peers.pop((src, port), None)
            else:
                peers[(src, port)] = now
            others = [p for p, seen in peers.items() if p != (src, port) and now - seen < 900]  # libtorrent re-announces at most every 300 s (min_announce_interval)
        compact = b"".join(socket.inet_aton(ip) + struct.pack("!H", p) for ip, p in others)
        body = bencode({"interval": 5, "min interval": 2, "peers": compact})
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def dump_events() -> None:
    while True:
        time.sleep(1)
        with LOCK:
            data = json.dumps(EVENTS)
        tmp = SHARE / "server_events.json.tmp"
        tmp.write_text(data)
        tmp.replace(SHARE / "server_events.json")


def main() -> None:
    setup()
    for target in (serve_dns, serve_udp_tracker_logger, dump_events):
        threading.Thread(target=target, daemon=True).start()
    (SHARE / "server_ready").write_text("ok")
    ThreadingHTTPServer(("0.0.0.0", 6969), Tracker).serve_forever()


if __name__ == "__main__":
    main()
